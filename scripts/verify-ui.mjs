import { chromium } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import assert from 'node:assert/strict'

await mkdir('artifacts', { recursive: true })
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = [], remote = []
page.on('pageerror', e => errors.push(e.message))
page.on('request', r => { if (/^https?:/.test(r.url()) && !r.url().startsWith('http://127.0.0.1:1420')) remote.push(r.url()) })
const view = name => page.getByLabel('编辑视图').getByLabel(name, { exact: true }).click()
try {
  await page.goto('http://127.0.0.1:1420')
  await page.getByRole('tab', { name: '欢迎.md', exact: true }).waitFor()
  await page.locator('.vditor-ir [contenteditable=true]').waitFor()
  await page.screenshot({ path: 'artifacts/markflow-live.png' })
  await view('源码编辑')
  const source = page.getByRole('textbox', { name: 'Markdown 源码' })
  const initial = await source.inputValue()
  await view('分屏编辑'); await view('阅读预览'); await view('可视化编辑'); await view('源码编辑')
  assert.equal(await source.inputValue(), initial, 'View changes must not rewrite source')
  const changed = '# 验证文档\n\n## 第一节\n\n**加粗** 和 ~~删除~~。\n\n- [x] 完成\n\n| A | B |\n| --- | --- |\n| 1 | 2 |\n\n## 第一节\n\n```md\n# 伪标题\n```\n'
  await source.fill(changed)
  await page.getByText('已保存', { exact: true }).waitFor()
  await view('分屏编辑')
  await page.waitForFunction(() => document.querySelectorAll('.document-panel:not([style*="display: none"]) .markdown-body h2').length === 2)
  assert.equal(await page.locator('.document-panel:visible .markdown-body h2').count(), 2)
  assert.equal(await page.locator('.outline-panel nav button').count(), 3, 'Code fences must not enter outline')
  assert.equal(await page.locator('.document-panel:visible .markdown-body table').count(), 1)
  assert.equal(await page.locator('.document-panel:visible .markdown-body input[type=checkbox][disabled]').count(), 1)
  await page.locator('.outline-panel nav button').last().click()
  assert((await source.evaluate(el => el.selectionStart)) > 40, 'Outline jumps to source position')
  await page.screenshot({ path: 'artifacts/markflow-split.png' })
  await page.getByRole('button', { name: '设置', exact: true }).click(); await page.getByRole('button', { name: '外观', exact: true }).click()
  await page.getByLabel('显示模式').getByText('暗色', { exact: true }).click()
  await page.getByRole('button', { name: '写作', exact: true }).click()
  await page.getByRole('combobox', { name: '正文字号', exact: true }).click()
  await page.getByRole('option', { name: '特大（20px）', exact: true }).click()
  await page.getByRole('button', { name: '通用', exact: true }).click(); await page.getByRole('combobox', { name: '默认编辑视图', exact: true }).click(); await page.getByRole('option', { name: '源码编辑', exact: true }).click()
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert(await page.locator('html').evaluate(el => el.classList.contains('dark')))
  await page.screenshot({ path: 'artifacts/markflow-dark.png' })
  await page.getByRole('button', { name: '写作清单.md', exact: true }).click()
  await page.getByRole('tab', { name: '写作清单.md', exact: true }).waitFor()
  assert((await page.getByRole('textbox', { name: 'Markdown 源码' }).inputValue()).includes('# 写作清单'))
  await page.getByRole('tab', { name: '欢迎.md', exact: true }).click()
  assert.equal(await source.inputValue(), changed, 'Tabs must retain independent content')
  await page.getByRole('button', { name: '新建文档', exact: true }).click()
  await page.getByLabel('名称', { exact: true }).fill('浏览器验证')
  await page.getByRole('button', { name: '确定', exact: true }).click()
  await page.getByRole('tab', { name: '浏览器验证.md', exact: true }).waitFor()
  await page.getByRole('textbox', { name: 'Markdown 源码' }).fill('# 新文档\n')
  await page.getByText('已保存', { exact: true }).waitFor()
  await page.getByRole('button', { name: '浏览器验证.md 的菜单', exact: true }).click()
  await page.getByRole('menuitem', { name: '重命名', exact: true }).click()
  await page.getByLabel('名称', { exact: true }).fill('已重命名.md')
  await page.getByRole('button', { name: '确定', exact: true }).click()
  await page.getByRole('tab', { name: '已重命名.md', exact: true }).waitFor()
  await page.getByRole('button', { name: '已重命名.md 的菜单', exact: true }).click()
  await page.getByRole('menuitem', { name: '移动到…', exact: true }).click()
  await page.getByLabel('目标目录', { exact: true }).fill('笔记')
  await page.getByRole('button', { name: '确定', exact: true }).click()
  await page.locator('.document-breadcrumb').filter({ hasText: '笔记/已重命名.md' }).waitFor()
  await view('可视化编辑')
  const live = page.locator('.document-panel:visible .vditor-ir [contenteditable=true]')
  await live.waitFor(); await live.press('Control+End'); await live.press('Enter'); await live.pressSequentially('实时编辑验证')
  await view('源码编辑')
  assert((await page.getByRole('textbox', { name: 'Markdown 源码' }).inputValue()).includes('实时编辑验证'))
  const standard = await page.evaluate(async () => {
    const {renderMarkdown, headings} = await import('/src/services/markdown.ts')
    const text = 'Setext\n======\n\n### H3\n\n> 引用\n>\n> - 嵌套列表\n\n1. 第一项\n2. 第二项\n\n**粗体** *斜体* ~~删除~~ `代码` &amp;\\*\n\n[引用链接][ref]\n\n[ref]: https://example.com\n\n<https://example.com>\n\n    indented code\n\n---\n\n<script>window.unsafe=true</script>\n\n<img src="assets/pic.png" onerror="window.unsafe=true"><iframe src="https://example.com"></iframe>\n'
    const parsed = new DOMParser().parseFromString(renderMarkdown(text), 'text/html')
    return { outline:headings(text).map(h=>h.level), h1:parsed.querySelector('h1')?.textContent, quote:!!parsed.querySelector('blockquote ul'), ordered:!!parsed.querySelector('ol'), strong:!!parsed.querySelector('strong'), emphasis:!!parsed.querySelector('em'), strike:!!parsed.querySelector('s'), code:!!parsed.querySelector('pre code'), unsafe:!!parsed.querySelector('script,iframe,[onerror]'), imgSrc:parsed.querySelector('img')?.getAttribute('src') }
  })
  assert.deepEqual(standard.outline, [1,3]); assert.equal(standard.h1, 'Setext')
  for (const key of ['quote','ordered','strong','emphasis','strike','code']) assert(standard[key], `Standard syntax: ${key}`)
  assert.equal(standard.unsafe, false); assert.equal(standard.imgSrc, null)
  await page.getByRole('textbox', {name:'Markdown 源码'}).fill('# 图片引用\n\n![保留](assets/missing.png)\n')
  await view('可视化编辑'); await live.waitFor(); await live.press('Control+End'); await live.press('Enter'); await live.pressSequentially('继续编辑')
  await view('源码编辑'); assert((await page.getByRole('textbox', {name:'Markdown 源码'}).inputValue()).includes('](assets/missing.png)'))
  await page.getByRole('button', { name: '笔记', exact: true }).click()
  await page.getByRole('button', { name: '已重命名.md 的菜单', exact: true }).click()
  await page.getByRole('menuitem', { name:'归档', exact:true }).click()
  await page.getByRole('alertdialog').getByRole('button', {name:'归档',exact:true}).click()
  await page.getByRole('tab', {name:'已重命名.md',exact:true}).waitFor({state:'hidden'})
  assert.deepEqual(errors, [], 'No browser runtime errors')
  assert.deepEqual(remote, [], 'No remote dependencies during local editing')
  console.log('UI verified: four views, source preservation, GFM, outline, themes, settings, tabs, create/rename/move and live editing. Screenshots saved to artifacts/.')
} catch (e) { await page.screenshot({ path: 'artifacts/markflow-test-failure.png' }); console.error('Runtime errors:', errors); throw e }
finally { await browser.close() }
